console.log("JavaScript Switch Conditionals")


let day = "Tuesday";
 
switch (day) {
  case "Monday":
    console.log("Start of the week!");
    break;
  case "Tuesday":
    console.log("Keep going, it’s only Tuesday!");
    break;
  case "Friday":
    console.log("Finally, Friday!");
    break;
  default:
    console.log("Just another day...");
}